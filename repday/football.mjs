const categories = [
  ['control','볼 컨트롤','01'],
  ['dribble','드리블','02'],
  ['pass','패스·첫 터치','03'],
  ['finish','슈팅·마무리','04'],
  ['movement','풋워크','05'],
  ['keeper','골키퍼','06']
];
const storageKey = 'harudodum-football-v1';
const dayKey = () => new Date(Date.now() + 9 * 60 * 60 * 1000).toISOString().slice(0, 10);

export function readProgress() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKey));
    if (saved?.completed && typeof saved.completed === 'object' && !Array.isArray(saved.completed)) return saved;
  } catch {
    // Start with an empty view if the saved progress cannot be read.
  }
  return {completed: {}};
}

export function updateFootballProgress(update) {
  const saved = readProgress();
  update(saved);
  try {
    localStorage.setItem(storageKey, JSON.stringify(saved));
    window.dispatchEvent(new Event('football-progress'));
    return true;
  } catch {
    return false;
  }
}

export function markFootballComplete(id) {
  return updateFootballProgress(saved => {
    const today = dayKey();
    const completed = new Set(Array.isArray(saved.completed[today]) ? saved.completed[today] : []);
    completed.add(id);
    saved.completed[today] = [...completed];
  });
}

export function initFootball() {
  const list = document.getElementById('football-list');
  const filters = document.getElementById('football-filters');
  const status = document.getElementById('football-status');
  let category = 'control';
  let currentDay = dayKey();

  function render() {
    currentDay = dayKey();
    const saved = readProgress();
    const checked = new Set(Array.isArray(saved.completed[currentDay]) ? saved.completed[currentDay] : []);
    const valid = drills.filter(drill => checked.has(drill.id));
    document.getElementById('football-completed').textContent = valid.length;
    document.getElementById('football-meter').value = valid.length;
    document.getElementById('football-category').textContent = categories.find(item => item[0] === category)[1];
    filters.querySelectorAll('button').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.category === category)));
    list.replaceChildren(...drills.filter(drill => drill.category === category).map((drill, index) => {
      const card = document.createElement('article');
      card.className = 'football-drill';
      const meta = document.createElement('p');
      meta.className = 'eyebrow';
      meta.textContent = 'DRILL ' + String(index + 1).padStart(2, '0') + ' · ' + drill.dose;
      const label = document.createElement('label');
      const input = document.createElement('input');
      input.type = 'checkbox';
      input.checked = checked.has(drill.id);
      input.setAttribute('aria-label', drill.name + ' 완료');
      const heading = document.createElement('span');
      heading.textContent = drill.name;
      label.append(input, heading);
      const equipment = document.createElement('p');
      equipment.className = 'football-equipment';
      equipment.textContent = drill.equipment;
      const point = document.createElement('p');
      point.textContent = drill.point;
      const visual = document.createElement('button');
      visual.type = 'button';
      visual.className = 'drill-visual-open';
      visual.textContent = '움직이는 동작 그림';
      visual.addEventListener('click', () => window.dispatchEvent(new CustomEvent('football-visual', {detail: drill.id})));
      const details = document.createElement('details');
      const summary = document.createElement('summary');
      summary.textContent = '훈련 방법 보기';
      const steps = document.createElement('ol');
      for (const step of drill.steps) {
        const item = document.createElement('li');
        item.textContent = step;
        steps.append(item);
      }
      details.append(summary, steps);
      input.addEventListener('change', () => {
        const latest = readProgress();
        const today = dayKey();
        const completed = new Set(Array.isArray(latest.completed[today]) ? latest.completed[today] : []);
        if (input.checked) completed.add(drill.id);
        else completed.delete(drill.id);
        latest.completed[today] = [...completed];
        try {
          localStorage.setItem(storageKey, JSON.stringify(latest));
          status.textContent = '이 기기에 훈련 기록을 저장했어요.';
        } catch {
          status.textContent = '이 브라우저에서는 훈련 기록을 저장할 수 없어요.';
        }
        const count = drills.filter(item => completed.has(item.id)).length;
        document.getElementById('football-completed').textContent = count;
        document.getElementById('football-meter').value = count;
      });
      card.append(meta, label, equipment, point, visual, details);
      return card;
    }));
  }

  for (const [id, title, number] of categories) {
    const button = document.createElement('button');
    button.type = 'button';
    button.dataset.category = id;
    const marker = document.createElement('span');
    marker.textContent = number;
    button.append(marker, document.createTextNode(title));
    button.addEventListener('click', () => {
      category = id;
      render();
    });
    filters.append(button);
  }
  window.addEventListener('football-progress', render);
  window.addEventListener('storage', event => {
    if (event.key === storageKey || event.key === null) render();
  });
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden && dayKey() !== currentDay) render();
  });
  setInterval(() => {
    if (dayKey() !== currentDay) render();
  }, 60000);
  render();
}
